class ApkInspection(NamedTuple):
    complete: bool
    signed: bool
    abis: list[str]
    signature_verification: str
    details: str = ""


class Tee:
    """Mirror Python and child-process output to the console and build log."""

    def __init__(self, *streams):
        self.streams = streams

    def write(self, value: str) -> int:
        for stream in self.streams:
            stream.write(value)
            stream.flush()
        return len(value)

    def flush(self) -> None:
        for stream in self.streams:
            stream.flush()


def enable_logging():
    RELEASE.mkdir(parents=True, exist_ok=True)
    log = LOG_PATH.open("w", encoding="utf-8")
    sys.stdout = Tee(sys.__stdout__, log)
    sys.stderr = Tee(sys.__stderr__, log)
    print(f"Build started: {datetime.now(timezone.utc).isoformat()}", flush=True)
    return log


def run_command(args: list[str], *, check: bool = True, cwd: Path = ROOT) -> int:
    """Stream combined output line-by-line; never hide a long-running command."""
    print("+", subprocess.list2cmdline(args), flush=True)
    process = subprocess.Popen(
        args,
        cwd=cwd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
        bufsize=1,
    )
    assert process.stdout is not None
    for line in process.stdout:
        print(line, end="", flush=True)
    return_code = process.wait()
    if check and return_code:
        raise subprocess.CalledProcessError(return_code, args)
    return return_code


def package_version(name: str) -> str:
    try:
        return importlib.metadata.version(name)
    except importlib.metadata.PackageNotFoundError:
        return "not installed"


def android_scaffolds() -> list[Path]:
    """Return Briefcase Android scaffold roots containing the Gradle project."""
    if not BUILD.exists():
        return []
    roots = {path.parent for path in BUILD.glob("*/android/gradle") if path.is_dir()}
    roots.update(path for path in BUILD.glob("*/android") if (path / "gradle").is_dir())
    return sorted(roots)


def gradle_projects() -> list[Path]:
    """Return Gradle roots generated by Briefcase, without assuming an app ID."""
    if not BUILD.exists():
        return []
    return sorted(
        {path.parent for path in BUILD.rglob("gradlew")}.union(
            path.parent for path in BUILD.rglob("gradlew.bat")
        )
    )


def clean_android() -> None:
    android_trees = (
        sorted(path for path in BUILD.glob("*/android") if path.is_dir())
        if BUILD.exists()
        else []
    )
    for tree in android_trees:
        print(f"Removing Android scaffold/cache: {tree}", flush=True)
        shutil.rmtree(tree)
    shutil.rmtree(ANDROID_RELEASE, ignore_errors=True)


def find_apks(suffix: str | None = None) -> list[Path]:
    """Search Briefcase output recursively; no fixed Gradle output path assumptions."""
    if not BUILD.exists():
        return []
    pattern = f"*{suffix}.apk" if suffix else "*.apk"
    return sorted(BUILD.rglob(pattern), key=lambda path: path.stat().st_mtime)


def find_android_tool(name: str) -> str | None:
    direct = shutil.which(name)
    if direct:
        return direct
    executable = f"{name}.exe" if os.name == "nt" else name
    for variable in ("ANDROID_HOME", "ANDROID_SDK_ROOT"):
        sdk = os.environ.get(variable)
        if not sdk:
            continue
        candidates = sorted(
            (Path(sdk) / "build-tools").glob(f"*/{executable}"), reverse=True
        )
        if candidates:
            return str(candidates[0])
    return None


def embedded_signature_exists(apk: Path) -> bool:
    """Detect JAR (v1) or APK Signing Block (v2+) signatures."""
    data = apk.read_bytes()
    if b"APK Sig Block 42" in data:
        return True
    try:
        with zipfile.ZipFile(apk) as archive:
            names = {name.upper() for name in archive.namelist()}
    except zipfile.BadZipFile:
        return False
    signature_files = any(
        name.startswith("META-INF/") and name.endswith((".RSA", ".DSA", ".EC"))
        for name in names
    )
    return signature_files and any(
        name.startswith("META-INF/") and name.endswith(".SF") for name in names
    )


def inspect_apk(apk: Path) -> ApkInspection:
    complete = False
    abis: list[str] = []
    details = ""
    try:
        with zipfile.ZipFile(apk) as archive:
            names = archive.namelist()
            complete = "AndroidManifest.xml" in names and "classes.dex" in names
            abis = sorted(
                {
                    name.split("/")[1]
                    for name in names
                    if name.startswith("lib/") and name.count("/") >= 2
                }
            )
    except (OSError, zipfile.BadZipFile) as exc:
        details = str(exc)
    signed = embedded_signature_exists(apk) if complete else False
    apksigner = find_android_tool("apksigner")
    if not apksigner:
        return ApkInspection(
            complete, signed, abis, "SIGNATURE VERIFY TOOL NOT AVAILABLE", details
        )
    result = subprocess.run(
        [apksigner, "verify", "--verbose", "--print-certs", str(apk)],
        cwd=ROOT,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    output = "\n".join(
        part.strip() for part in (result.stdout, result.stderr) if part.strip()
    )
    if output:
        print(output, flush=True)
    return ApkInspection(
        complete,
        signed and result.returncode == 0,
        abis,
        "PASS" if result.returncode == 0 else "FAIL",
        output,
    )


def is_installable(inspection: ApkInspection) -> bool:
    """An APK is installable only when its required contents and signature exist."""
    return inspection.complete and inspection.signed


def artifact_name(kind: str, *, signed: bool = False) -> str:
    if kind == "debug":
        return f"{APP_FILENAME}-{APP_VERSION}-debug.apk"
    suffix = "release" if signed else "release-unsigned"
    return f"{APP_FILENAME}-{APP_VERSION}-{suffix}.apk"


def copy_apk(source: Path, kind: str, *, signed: bool = False) -> tuple[Path, int, str]:
    destination = ANDROID_RELEASE / artifact_name(kind, signed=signed)
    ANDROID_RELEASE.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, destination)
    size = destination.stat().st_size
    digest = hashlib.sha256(destination.read_bytes()).hexdigest()
    print(f"APK type: {kind}")
    print(f"APK created: {destination.resolve()}")
    print(f"Size: {size / 1048576:.2f} MB")
    print(f"SHA256: {digest}")
    if size / 1048576 > BUILD_SIZE_WARNING_MB:
        print("WARNING: APK is larger than the configured size warning threshold.")
    return destination, size, digest


