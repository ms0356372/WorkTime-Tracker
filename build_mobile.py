def build_android(
    clean: bool,
    mode: str = "debug",
    require_release_signing: bool = False,
) -> int:
    state: dict[str, str] = {"final": "FAIL"}
    try:
        validate_configuration()
        if (
            mode == "release"
            and require_release_signing
            and not release_signing_configured()
        ):
            missing = ", ".join(
                name for name in SIGNING_ENV_VARS if not os.environ.get(name)
            )
            raise RuntimeError(
                f"Release signing is not configured. Set keystore credentials outside Git: {missing}"
            )
        if clean:
            clean_android()
        print("[TEST] Running project tests...", flush=True)
        state["tests"] = "FAIL"
        run_command([sys.executable, "-m", "pytest", "-q"])
        state["tests"] = "PASS"
        if android_scaffolds():
            print(
                "[UPDATE] Existing Android scaffold found; running Briefcase update.",
                flush=True,
            )
            state["scaffold"] = "UPDATE FAIL"
            run_command([sys.executable, "-m", "briefcase", "update", "android"])
            state["scaffold"] = "UPDATE PASS"
        else:
            print(
                "[CREATE] No Android scaffold found; running Briefcase create once.",
                flush=True,
            )
            state["scaffold"] = "CREATE FAIL"
            run_command([sys.executable, "-m", "briefcase", "create", "android"])
            state["scaffold"] = "CREATE PASS"
        configure_android_backup_policy()
        validate_generated_gradle_dependencies()
        print(f"[BUILD] Building Android {mode} application...", flush=True)
        state["build"] = "FAIL"
        run_command([sys.executable, "-m", "briefcase", "build", "android"])
        state["build"] = "PASS"
        state["package"] = "FAIL"
        if mode == "debug":
            apk, size, digest = copy_apk(obtain_debug_apk(), "debug")
        else:
            package_started = datetime.now().timestamp()
            print("[PACKAGE] Packaging release APK and AAB...", flush=True)
            run_command(
                [sys.executable, "-m", "briefcase", "package", "android", "-p", "apk"]
            )
            candidates = [
                path
                for path in find_apks()
                if "debug" not in path.name.lower()
                and path.stat().st_mtime >= package_started - 2
            ]
            if not candidates:
                raise RuntimeError(
                    "Release package completed but no newly generated release APK was found."
                )
            unsigned_apk, _, _ = copy_apk(candidates[-1], "release", signed=False)
            apk = (
                sign_release_apk(unsigned_apk)
                if release_signing_configured()
                else unsigned_apk
            )
            size = apk.stat().st_size
            digest = hashlib.sha256(apk.read_bytes()).hexdigest()
            if not release_signing_configured():
                print("UNSIGNED RELEASE APK", flush=True)
            try:
                run_command(
                    [
                        sys.executable,
                        "-m",
                        "briefcase",
                        "package",
                        "android",
                        "-p",
                        "aab",
                    ]
                )
                aabs = sorted(
                    BUILD.rglob("*.aab"), key=lambda path: path.stat().st_mtime
                )
                if aabs:
                    ANDROID_RELEASE.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(
                        aabs[-1], ANDROID_RELEASE / f"{APP_FILENAME}-{APP_VERSION}.aab"
                    )
            except subprocess.CalledProcessError:
                print(
                    "WARNING: AAB packaging failed; APK status will still be reported."
                )
        state["package"] = "PASS"
        inspection = inspect_apk(apk)
        installable = is_installable(inspection)
        state.update(
            apk_type=mode.upper(),
            signed="YES" if inspection.signed else "NO",
            installable="YES" if installable else "NO",
            abi="\n".join(inspection.abis) or "N/A",
            apk_path=str(apk.resolve()),
            apk_size=f"{size / 1048576:.2f} MB",
            sha256=digest,
            signature_verification=inspection.signature_verification,
        )
        if mode == "debug" and not installable:
            raise RuntimeError(
                "Debug APK is incomplete or unsigned and cannot be installed."
            )
        state["final"] = "PASS"
        write_report(state)
        if mode == "debug":
            print_debug_ready(apk, size)
        return 0
    except Exception as exc:
        state["error"] = str(exc)
        write_report(state)
        print(f"BUILD FAILED: {exc}", file=sys.stderr, flush=True)
        return 1


def ios_scaffolds() -> list[Path]:
    if not BUILD.exists():
        return []
    return sorted(path for path in BUILD.glob("*/iOS") if path.is_dir())


def build_ios() -> int:
    """Retain the macOS Briefcase iOS path; signing remains an Xcode task."""
    if platform.system() != "Darwin":
        print("iOS builds require macOS and Xcode.", file=sys.stderr)
        return 1
    try:
        command = "update" if ios_scaffolds() else "create"
        run_command([sys.executable, "-m", "briefcase", command, "iOS"])
        run_command([sys.executable, "-m", "briefcase", "build", "iOS"])
        run_command([sys.executable, "-m", "briefcase", "package", "iOS"])
        return 0
    except Exception as exc:
        print(f"iOS BUILD FAILED: {exc}", file=sys.stderr)
        return 1


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="WorkTime Tracker mobile build tool")
    parser.add_argument(
        "action",
        choices=("android", "ios", "all", "test", "clean", "doctor"),
        nargs="?",
        default="android",
    )
    parser.add_argument(
        "--clean",
        action="store_true",
        help="Remove Android scaffold/cache before rebuilding",
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument(
        "--debug",
        action="store_const",
        const="debug",
        dest="mode",
        help="Build a signed debug APK (default)",
    )
    mode.add_argument(
        "--release",
        action="store_const",
        const="release",
        dest="mode",
        help="Build release APK/AAB artifacts",
    )
    parser.set_defaults(mode="debug")
    parser.add_argument(
        "--require-release-signing", action="store_true", help=argparse.SUPPRESS
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    if args.action == "doctor":
        return doctor()
    if args.action == "test":
        return run_command([sys.executable, "-m", "pytest", "-q"], check=False)
    if args.action == "clean":
        clean_android()
        return 0
    if args.action == "android":
        return build_android(args.clean, args.mode, args.require_release_signing)
    if args.action == "ios":
        return build_ios()
    if args.action == "all":
        android_result = build_android(
            args.clean, args.mode, args.require_release_signing
        )
        return android_result or build_ios()
    return 2


if __name__ == "__main__":
    log_handle = enable_logging()
    try:
        exit_code = main()
    finally:
        sys.stdout = sys.__stdout__
        sys.stderr = sys.__stderr__
        log_handle.close()
    raise SystemExit(exit_code)
