def validate_configuration() -> None:
    data = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    backend = data.get("build-system", {}).get("build-backend")
    if backend != "setuptools.build_meta":
        raise RuntimeError(
            f"Unsupported Python build backend: {backend!r}. Expected setuptools.build_meta."
        )
    app = data["tool"]["briefcase"]["app"]["worktime_tracker"]
    if "src/worktime_tracker" not in app["sources"]:
        raise RuntimeError("Briefcase sources must include src/worktime_tracker.")
    if "android" not in app:
        raise RuntimeError("Briefcase Android configuration is missing.")
    android = app["android"]
    if MATERIAL_DEPENDENCY not in android.get("build_gradle_dependencies", []):
        raise RuntimeError(
            f"OptionContainer requires Android Gradle dependency {MATERIAL_DEPENDENCY}."
        )
    policy = json.loads(BACKUP_POLICY.read_text(encoding="utf-8"))
    if policy.get("application_attributes", {}).get("allowBackup") != "false":
        raise RuntimeError("Android backup policy must set allowBackup to false.")
    for rules in (BACKUP_RULES, BACKUP_RULES_LEGACY):
        ET.parse(rules)


def validate_generated_gradle_dependencies() -> None:
    """Confirm Briefcase persisted required Maven dependencies into Gradle."""
    gradle_files = (
        sorted([*BUILD.rglob("build.gradle"), *BUILD.rglob("build.gradle.kts")])
        if BUILD.exists()
        else []
    )
    app_gradle_files = [path for path in gradle_files if path.parent.name == "app"]
    if not app_gradle_files:
        raise RuntimeError("Generated Android app/build.gradle was not found.")
    if not any(
        MATERIAL_DEPENDENCY in path.read_text(encoding="utf-8")
        for path in app_gradle_files
    ):
        locations = ", ".join(str(path) for path in app_gradle_files)
        raise RuntimeError(
            f"Generated Gradle is missing {MATERIAL_DEPENDENCY}: {locations}"
        )
    print(
        f"Android Gradle dependency verified: implementation '{MATERIAL_DEPENDENCY}'",
        flush=True,
    )


def android_manifests() -> list[Path]:
    """Find generated application manifests without assuming an app folder name."""
    if not BUILD.exists():
        return []
    return sorted(
        path
        for path in BUILD.rglob("AndroidManifest.xml")
        if path.parent.name == "main" and path.parent.parent.name == "src"
    )


def configure_android_backup_policy() -> None:
    """Reapply the repository-owned policy after every Briefcase create/update."""
    attributes = json.loads(BACKUP_POLICY.read_text(encoding="utf-8"))[
        "application_attributes"
    ]
    manifests = android_manifests()
    if not manifests:
        raise RuntimeError("Generated Android application manifest was not found.")
    ET.register_namespace("android", ANDROID_NAMESPACE)
    for manifest in manifests:
        tree = ET.parse(manifest)
        application = tree.getroot().find("application")
        if application is None:
            raise RuntimeError(
                f"Android manifest has no application element: {manifest}"
            )
        for name, value in attributes.items():
            application.set(f"{{{ANDROID_NAMESPACE}}}{name}", value)
        resource_directory = manifest.parent / "res" / "xml"
        resource_directory.mkdir(parents=True, exist_ok=True)
        shutil.copy2(BACKUP_RULES, resource_directory / BACKUP_RULES.name)
        shutil.copy2(
            BACKUP_RULES_LEGACY,
            resource_directory / BACKUP_RULES_LEGACY.name,
        )
        tree.write(manifest, encoding="utf-8", xml_declaration=True)
    validate_android_backup_policy()


def validate_android_backup_policy() -> None:
    expected = json.loads(BACKUP_POLICY.read_text(encoding="utf-8"))[
        "application_attributes"
    ]
    for manifest in android_manifests():
        application = ET.parse(manifest).getroot().find("application")
        if application is None or any(
            application.get(f"{{{ANDROID_NAMESPACE}}}{name}") != value
            for name, value in expected.items()
        ):
            raise RuntimeError(f"Android automatic backup is not disabled: {manifest}")
        resource_directory = manifest.parent / "res" / "xml"
        for rules in (BACKUP_RULES, BACKUP_RULES_LEGACY):
            generated = resource_directory / rules.name
            if not generated.is_file() or generated.read_bytes() != rules.read_bytes():
                raise RuntimeError(
                    f"Generated Android backup rules are missing: {generated}"
                )
    print("Android Auto Backup/Restore policy verified: DISABLED", flush=True)


def doctor() -> int:
    """Report prerequisites without rejecting Briefcase-managed Java or Android SDK."""
    validate_configuration()
    java = shutil.which("java")
    briefcase_installed = package_version("briefcase") != "not installed"
    print(f"Python executable: {sys.executable}")
    print(f"Python version: {platform.python_version()}")
    print(f"Project root: {ROOT}")
    print(
        f"Virtual environment: {sys.prefix != getattr(sys, 'base_prefix', sys.prefix)} ({sys.prefix})"
    )
    print(f"Briefcase version: {package_version('briefcase')}")
    print(f"Java availability: {java or 'not found on PATH'}")
    print(f"JAVA_HOME: {os.environ.get('JAVA_HOME', 'not set')}")
    print(
        f"Android SDK availability: {os.environ.get('ANDROID_HOME') or os.environ.get('ANDROID_SDK_ROOT') or 'not set'}"
    )
    print(f"ANDROID_HOME: {os.environ.get('ANDROID_HOME', 'not set')}")
    pyproject = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    print(f"pyproject.toml: {(ROOT / 'pyproject.toml').is_file()}")
    print(f"Python build backend: {pyproject['build-system']['build-backend']}")
    print(f"Android scaffold: {android_scaffolds() or 'not created'}")
    print(f"Release directory: {RELEASE}")
    if java:
        print("System Java detected (Android builds require JDK 17):")
        run_command([java, "-version"], check=False)
    else:
        print("Briefcase-managed Java/Android SDK will be used when available.")
    if briefcase_installed:
        run_command([sys.executable, "-m", "briefcase", "--version"], check=False)
    else:
        print("Briefcase is not installed in this Python environment.")
    return 0


def run_gradle_debug() -> None:
    java_home = os.environ.get("JAVA_HOME")
    java_name = "java.exe" if os.name == "nt" else "java"
    java_from_home = Path(java_home) / "bin" / java_name if java_home else None
    if java_from_home and not java_from_home.is_file():
        raise RuntimeError(
            f"Gradle fallback cannot run because JAVA_HOME is invalid: {java_home}"
        )
    if not java_from_home and not shutil.which("java"):
        raise RuntimeError(
            "Gradle fallback requires JAVA_HOME or a java executable on PATH. "
            "Briefcase did not produce a debug APK."
        )
    projects = gradle_projects()
    if not projects:
        raise RuntimeError(
            "Briefcase Android Gradle project was not found after create/update."
        )
    project = projects[-1]
    wrapper = project / ("gradlew.bat" if os.name == "nt" else "gradlew")
    command = [str(wrapper), "assembleDebug"]
    run_command(command, cwd=project)


def obtain_debug_apk() -> Path:
    """Use Briefcase's debug artifact, falling back to Gradle only when absent."""
    candidates = find_apks("-debug")
    if candidates:
        apk = candidates[-1]
        print(f"[PACKAGE] Using Debug APK produced by Briefcase: {apk}", flush=True)
        return apk

    print(
        "[PACKAGE] Briefcase produced no Debug APK; falling back to Gradle assembleDebug.",
        flush=True,
    )
    run_gradle_debug()
    candidates = find_apks("-debug")
    if not candidates:
        raise RuntimeError(
            "Gradle assembleDebug completed but no newly generated *-debug.apk was found."
        )
    return candidates[-1]


def release_signing_configured() -> bool:
    return all(os.environ.get(name) for name in SIGNING_ENV_VARS)


def sign_release_apk(unsigned_apk: Path) -> Path:
    apksigner = find_android_tool("apksigner")
    if not apksigner:
        raise RuntimeError(
            "Release signing is configured, but apksigner is unavailable."
        )
    keystore = Path(os.environ["ANDROID_KEYSTORE"]).expanduser()
    if not keystore.is_file():
        raise RuntimeError(f"Release keystore was not found: {keystore}")
    signed_apk = ANDROID_RELEASE / artifact_name("release", signed=True)
    shutil.copy2(unsigned_apk, signed_apk)
    run_command(
        [
            apksigner,
            "sign",
            "--ks",
            str(keystore),
            "--ks-key-alias",
            os.environ["ANDROID_KEY_ALIAS"],
            "--ks-pass",
            "env:ANDROID_KEYSTORE_PASSWORD",
            "--key-pass",
            "env:ANDROID_KEY_PASSWORD",
            str(signed_apk),
        ]
    )
    return signed_apk


